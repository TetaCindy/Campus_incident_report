import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'providers/auth_provider.dart';
import 'providers/incident_provider.dart';
import 'screens/login_screen.dart';
import 'screens/main_shell.dart';
import 'screens/verify_email_screen.dart';
import 'services/auth_service.dart';
import 'services/incident_service.dart';
import 'theme/app_theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const App());
}

class App extends StatelessWidget {
  const App({super.key});

  @override
  Widget build(BuildContext context) {
    return MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => AuthProvider(AuthService())),
        ChangeNotifierProxyProvider<AuthProvider, IncidentProvider>(
          create: (_) => IncidentProvider(IncidentService()),
          update: (_, auth, prev) => prev!..bindUser(auth.firebaseUser?.uid, auth.verified),
        ),
      ],
      child: MaterialApp(
        title: 'Campus Incident Reporter',
        debugShowCheckedModeBanner: false,
        theme: buildTheme(),
        home: const AuthGate(),
      ),
    );
  }
}

/// Decides which screen to show from the auth state: login -> verify email -> app.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) {
    final auth = context.watch<AuthProvider>();
    if (auth.initializing) return const Scaffold(body: Center(child: CircularProgressIndicator()));
    if (!auth.loggedIn) return const LoginScreen();
    if (!auth.verified) return const VerifyEmailScreen();
    return const MainShell();
  }
}
